"""KAISER — Backtesting & Strategy Evaluation Domain Models.

Provides strongly-typed, immutable data structures for historical backtesting,
virtual portfolio tracking, simulated orders, fills, performance metrics,
and strategy evaluation outcomes.

SAFETY INVARIANTS:
1. Purely simulated/hypothetical: Never connects to a live broker or exchange.
2. Distinct from real execution engine: All fills are simulated locally.
3. Anti-look-ahead modeling: Explicit timestamping for signal evaluation and execution.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

from app.analysis.models import normalize_timeframe
from app.core.exceptions import ValidationError


class OrderSide(str, Enum):
    """Side of a simulated trading order."""

    BUY = "BUY"
    SELL = "SELL"


class OrderType(str, Enum):
    """Execution type of a simulated order."""

    MARKET = "MARKET"
    LIMIT = "LIMIT"


class OrderStatus(str, Enum):
    """Lifecycle status of a simulated order."""

    PENDING = "PENDING"
    FILLED = "FILLED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"


class SignalType(str, Enum):
    """Categorical signal emitted by a Strategy."""

    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    CLOSE = "CLOSE"


class ExecutionModel(str, Enum):
    """Simulated execution timing model."""

    NEXT_BAR_OPEN = "next_bar_open"
    CURRENT_BAR_CLOSE = "current_bar_close"


class BacktestStatus(str, Enum):
    """Overall execution status of a backtest session."""

    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"
    FAILED = "FAILED"


class PositionSizeType(str, Enum):
    """Position sizing methodology."""

    FIXED_QUANTITY = "fixed_quantity"
    FIXED_CASH = "fixed_cash"
    PERCENT_EQUITY = "percent_equity"


class FeeModel(str, Enum):
    """Fee calculation structure."""

    PERCENTAGE = "percentage"
    FIXED = "fixed"


@dataclass(frozen=True)
class StrategySignal:
    """Hypothetical trading signal generated by a Strategy.

    Attributes:
        symbol: Ticker symbol.
        timestamp: Simulation timestamp when signal was evaluated.
        signal_type: BUY, SELL, HOLD, or CLOSE.
        strength: Confidence or weight (0.0 to 1.0).
        suggested_quantity: Optional target trade quantity.
        suggested_price: Optional limit or reference price.
        reason: Optional human/voice explanation for why signal was emitted.
        metadata: Additional arbitrary contextual tags.
    """

    symbol: str
    timestamp: float
    signal_type: SignalType
    strength: float = 1.0
    suggested_quantity: Optional[float] = None
    suggested_price: Optional[float] = None
    reason: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.symbol or not isinstance(self.symbol, str) or not self.symbol.strip():
            raise ValidationError("StrategySignal symbol must be a non-empty string.")
        object.__setattr__(self, "symbol", self.symbol.strip().upper())

        if self.timestamp <= 0:
            raise ValidationError(f"StrategySignal timestamp must be positive, got {self.timestamp}")

        if not isinstance(self.signal_type, SignalType):
            try:
                st = SignalType(str(self.signal_type).upper())
                object.__setattr__(self, "signal_type", st)
            except Exception:
                raise ValidationError(f"Invalid SignalType: {self.signal_type}")

        if self.strength < 0.0 or self.strength > 1.0:
            raise ValidationError(f"StrategySignal strength must be between 0.0 and 1.0, got {self.strength}")

        if self.suggested_quantity is not None and self.suggested_quantity <= 0:
            raise ValidationError("suggested_quantity must be positive when specified.")

    def to_dict(self) -> Dict[str, Any]:
        """Convert signal to dictionary representation."""
        return {
            "symbol": self.symbol,
            "timestamp": self.timestamp,
            "signal_type": self.signal_type.value,
            "strength": self.strength,
            "suggested_quantity": self.suggested_quantity,
            "suggested_price": self.suggested_price,
            "reason": self.reason,
            "metadata": dict(self.metadata),
        }


@dataclass(frozen=True)
class SimulatedOrder:
    """Virtual order submitted to the SimulatedPortfolio.

    Attributes:
        order_id: Unique order identifier.
        symbol: Ticker symbol.
        side: BUY or SELL.
        order_type: MARKET or LIMIT.
        quantity: Share or contract quantity.
        price: Requested or limit price.
        created_at: Simulation timestamp when order was placed.
        status: Current order status.
        filled_at: Simulation timestamp when filled.
        fill_price: Executed price.
        fee: Transaction fee applied.
        slippage: Slippage amount applied.
        rejection_reason: Explanatory error message if rejected.
        correlation_id: Tracing correlation ID.
    """

    order_id: str
    symbol: str
    side: OrderSide
    order_type: OrderType
    quantity: float
    price: Optional[float] = None
    created_at: float = 0.0
    status: OrderStatus = OrderStatus.PENDING
    filled_at: Optional[float] = None
    fill_price: Optional[float] = None
    fee: float = 0.0
    slippage: float = 0.0
    rejection_reason: Optional[str] = None
    correlation_id: Optional[str] = None

    def __post_init__(self) -> None:
        if not self.order_id or not isinstance(self.order_id, str):
            raise ValidationError("SimulatedOrder order_id must be a non-empty string.")
        if not self.symbol or not isinstance(self.symbol, str):
            raise ValidationError("SimulatedOrder symbol must be a non-empty string.")
        object.__setattr__(self, "symbol", self.symbol.strip().upper())

        if not isinstance(self.side, OrderSide):
            object.__setattr__(self, "side", OrderSide(str(self.side).upper()))

        if not isinstance(self.order_type, OrderType):
            object.__setattr__(self, "order_type", OrderType(str(self.order_type).upper()))

        if not isinstance(self.status, OrderStatus):
            object.__setattr__(self, "status", OrderStatus(str(self.status).upper()))

        if self.quantity <= 0:
            raise ValidationError(f"SimulatedOrder quantity must be positive, got {self.quantity}")

    def to_dict(self) -> Dict[str, Any]:
        """Convert order to dictionary."""
        return {
            "order_id": self.order_id,
            "symbol": self.symbol,
            "side": self.side.value,
            "order_type": self.order_type.value,
            "quantity": self.quantity,
            "price": self.price,
            "created_at": self.created_at,
            "status": self.status.value,
            "filled_at": self.filled_at,
            "fill_price": self.fill_price,
            "fee": self.fee,
            "slippage": self.slippage,
            "rejection_reason": self.rejection_reason,
            "correlation_id": self.correlation_id,
        }


@dataclass(frozen=True)
class SimulatedFill:
    """Execution receipt representing a simulated fill.

    Attributes:
        fill_id: Unique fill identifier.
        order_id: Originating order ID.
        symbol: Ticker symbol.
        side: BUY or SELL.
        quantity: Executed quantity.
        price: Execution price after slippage and half-spread.
        fee: Explicit commission or transaction fee.
        slippage_cost: Total monetary cost from slippage.
        timestamp: Simulation timestamp when fill took place.
        correlation_id: Tracing correlation ID.
    """

    fill_id: str
    order_id: str
    symbol: str
    side: OrderSide
    quantity: float
    price: float
    fee: float
    slippage_cost: float
    timestamp: float
    correlation_id: Optional[str] = None

    def __post_init__(self) -> None:
        if not self.fill_id:
            raise ValidationError("SimulatedFill fill_id is required.")
        if not self.order_id:
            raise ValidationError("SimulatedFill order_id is required.")
        if self.quantity <= 0:
            raise ValidationError(f"SimulatedFill quantity must be positive, got {self.quantity}")
        if self.price <= 0:
            raise ValidationError(f"SimulatedFill price must be positive, got {self.price}")
        if self.fee < 0:
            raise ValidationError(f"SimulatedFill fee cannot be negative, got {self.fee}")
        if self.timestamp <= 0:
            raise ValidationError(f"SimulatedFill timestamp must be positive, got {self.timestamp}")

    def to_dict(self) -> Dict[str, Any]:
        """Convert fill to dictionary."""
        return {
            "fill_id": self.fill_id,
            "order_id": self.order_id,
            "symbol": self.symbol,
            "side": self.side.value if hasattr(self.side, "value") else str(self.side),
            "quantity": self.quantity,
            "price": round(self.price, 4),
            "fee": round(self.fee, 4),
            "slippage_cost": round(self.slippage_cost, 4),
            "timestamp": self.timestamp,
            "correlation_id": self.correlation_id,
        }


@dataclass(frozen=True)
class TradeRecord:
    """Audit record for a completed round-trip simulated trade.

    Attributes:
        trade_id: Unique trade identifier.
        symbol: Ticker symbol.
        side: Entry side (BUY for long).
        entry_time: Simulation timestamp of entry.
        exit_time: Simulation timestamp of exit.
        entry_price: Average entry fill price.
        exit_price: Average exit fill price.
        quantity: Executed quantity.
        gross_pnl: Gross profit or loss before fees.
        net_pnl: Net profit or loss after fees and slippage.
        fees: Total fees paid across entry and exit.
        slippage: Total slippage cost across entry and exit.
        return_pct: Percentage return on capital committed.
        duration_seconds: Holding duration in simulation seconds.
        is_win: True if net_pnl > 0.
    """

    trade_id: str
    symbol: str
    side: OrderSide
    entry_time: float
    exit_time: float
    entry_price: float
    exit_price: float
    quantity: float
    gross_pnl: float
    net_pnl: float
    fees: float
    slippage: float
    return_pct: float
    duration_seconds: float
    is_win: bool

    def to_dict(self) -> Dict[str, Any]:
        """Convert trade record to dictionary."""
        return {
            "trade_id": self.trade_id,
            "symbol": self.symbol,
            "side": self.side.value if hasattr(self.side, "value") else str(self.side),
            "entry_time": self.entry_time,
            "exit_time": self.exit_time,
            "entry_price": round(self.entry_price, 4),
            "exit_price": round(self.exit_price, 4),
            "quantity": self.quantity,
            "gross_pnl": round(self.gross_pnl, 2),
            "net_pnl": round(self.net_pnl, 2),
            "fees": round(self.fees, 4),
            "slippage": round(self.slippage, 4),
            "return_pct": round(self.return_pct, 2),
            "duration_seconds": round(self.duration_seconds, 1),
            "is_win": self.is_win,
        }


